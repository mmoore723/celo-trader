import assert from 'node:assert/strict';
const {chromium}=await import(process.env.CELO_PLAYWRIGHT_MODULE || 'playwright');
const browser=await chromium.launch({channel:'chrome',headless:true});
const page=await browser.newPage({viewport:{width:700,height:900}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:5174/tests/live-activity-feed.fixture.html');
await page.waitForSelector('.activity-entry');
assert.equal(await page.locator('.activity-entry').count(),12);
assert.equal(await page.locator('.activity-entry.latest').count(),1);
assert.equal(await page.locator('.activity-checks [data-state=passed]').count(),12);
assert.equal(await page.locator('.activity-checks [data-state=pending]').count(),12);
await page.getByRole('button',{name:'Pause feed'}).click();
await page.getByRole('button',{name:'Add update',exact:true}).click();
assert.equal(await page.locator('.activity-entry').count(),12);
await page.getByRole('button',{name:'Show newest updates'}).click();
assert.equal(await page.locator('.activity-entry').count(),13);
assert.match(await page.locator('.latest').innerText(),/New unique update/);
await page.getByRole('textbox',{name:'Filter activity'}).fill('SPY');
assert.equal(await page.locator('.activity-entry').count(),1);
await page.getByRole('textbox',{name:'Filter activity'}).fill('');
await page.locator('.activity-checks summary').first().click();
await page.getByRole('button',{name:'Show newest updates'}).waitFor({state:'visible'});
await page.setViewportSize({width:360,height:800});
assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
await page.getByRole('button',{name:'Theme',exact:true}).click();
assert.ok(await page.locator('html').evaluate(e=>e.classList.contains('dark')));
await page.getByRole('button',{name:'Theme',exact:true}).click();
await page.screenshot({path:'/tmp/celo-feed-verified.png',fullPage:true});
assert.deepEqual(errors,[]);await browser.close();console.log('PASS: cards, exact checks, newest, pause, filter, details, mobile, theme, no browser errors');
