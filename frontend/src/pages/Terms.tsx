interface TermsProps {
  /** If true: already-accepted user is just reviewing; show "Back" instead of Accept/Decline */
  viewOnly?: boolean;
}

export function Terms({ viewOnly = false }: TermsProps) {
  const { acceptTerms, logout } = useAuth();
  const [busy, setBusy] = useState(false);

  async function handleAccept() {
    setBusy(true);
    try { await acceptTerms(); }
    finally { setBusy(false); }
  }

  return (
    <div style={s.backdrop}>
      <div style={s.card}>
        <div style={s.header}>
          <span style={s.badge}>Legal Disclosure</span>
          <h1 style={s.title}>Terms of Service</h1>
          <p style={s.subtitle}>
            {viewOnly
              ? "Celo Trader Terms of Service — for reference."
              : "Please read the following disclosure carefully before using Celo Trader. You must agree to continue."}
          </p>
        </div>

        <div style={s.scroll}>
          {SECTIONS.map((sec) => (
            <div key={sec.heading} style={s.section}>
              <h3 style={s.secTitle}>{sec.heading}</h3>
              <p style={s.secBody}>{sec.body}</p>
            </div>
          ))}
          <p style={s.lastUpdated}>Last updated: July 2026 · Version 1.0</p>
        </div>

        <div style={s.footer}>
          {viewOnly ? (
            <button style={s.acceptBtn} onClick={() => window.history.back()}>
              ← Back to Dashboard
            </button>
          ) : (
            <>
              <button style={s.declineBtn} onClick={logout} disabled={busy}>
                Decline &amp; Sign Out
              </button>
              <button style={{ ...s.acceptBtn, opacity: busy ? 0.7 : 1 }}
                      onClick={handleAccept} disabled={busy}>
                {busy ? "Saving…" : "I Agree — Enter Dashboard"}
              </button>
            </>
          )}
        </div>
      </div>
    </div>
  );
}

